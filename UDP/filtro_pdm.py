# === CIC ===
def cic_filter(signal: np.ndarray, R: int, N: int, M: int = 1) -> np.ndarray:
    # integradores
    x = signal.astype(np.int64, copy=False)
    for _ in range(N):
        x = np.cumsum(x)
    # decimação
    x = x[::R]
    # combs
    for _ in range(N):
        x = np.concatenate(([0], np.diff(x, n=1)))
    return x[M:]

# === FIR ===
def fir_filter(signal: np.ndarray, coeffs: np.ndarray) -> np.ndarray:
    return np.convolve(signal.astype(np.float64, copy=False), coeffs, mode="same")

def processar_pdm(sinal_pdm: np.ndarray) -> np.ndarray:
    """
    Entrada: sinal PDM já bipolar (-1/+1), tipo int8/int16/float.
    Saída: sinal final filtrado (CIC+FIR), já decimado por R.
    """
    cic_out = cic_filter(sinal_pdm, R, N, M)
    fir_out = fir_filter(cic_out, fir_coeffs)
    return fir_out